/// The bytes a vector's hex spells; the vectors are constants, so a bad digit is an engine
/// bug.
fn hex(s: &str) -> Vec<u8> {
    let digits: Vec<u8> = s.bytes().filter(|b| !b.is_ascii_whitespace()).collect();
    digits
        .chunks(2)
        .map(|p| {
            let s = core::str::from_utf8(p).expect("ASCII");
            u8::from_str_radix(s, 16).expect("a self-test vector is hex")
        })
        .collect()
}

/// Whether `family` gives every answer `v` holds.
fn check(family: Family, v: &Vectors<'_>, platform: &mut impl Platform) -> bool {
    match family {
        Family::Hash => {
            let sha = Hash::Sha256.digest(&[b"abc"]);
            let mac = crypto::hmac(Hash::Sha256, b"Jefe", &[b"what do ya want for nothing?"]);
            let a = crypto::kdfa(
                Hash::Sha256,
                b"janus key",
                b"janus label",
                b"context u",
                b"context v",
                512,
            );
            let e =
                crypto::kdfe(Hash::Sha256, b"janus z", b"janus label", b"party u", b"party v", 256);
            sha.as_slice() == hex(v.sha256_abc)
                && mac[..] == hex(v.hmac_jefe)[..]
                && a[..] == hex(v.kdfa)[..]
                && e[..] == hex(v.kdfe)[..]
        }
        Family::Aes => {
            let key: [u8; 16] = hex("2b7e151628aed2a6abf7158809cf4f3c").try_into().expect("16");
            let iv: [u8; 16] = hex("000102030405060708090a0b0c0d0e0f").try_into().expect("16");
            let plain = hex("6bc1bee22e409f96e93d7e117393172aae2d8a571e03ac9c9eb76fac45af8e51");
            let mut buf = plain.clone();
            crypto::aes128_cfb_encrypt(&key, &iv, &mut buf);
            let encrypted = buf == hex(v.aes_cfb);
            crypto::aes128_cfb_decrypt(&key, &iv, &mut buf);
            encrypted && buf == plain
        }
        Family::Ecc => {
            let Some(key) = EccPrivate::from_bytes(&hex(v.ecc_x)) else { return false };
            let (ux, uy) = key.public();
            let digest: [u8; 32] =
                Hash::Sha256.digest(&[b"sample"]).as_slice().try_into().expect("32");
            let (r, s) = key.sign(&digest);
            let Some(peer) = EccPublicKey::from_coordinates(&ux, &uy) else { return false };
            let Some(k) = EccPrivate::from_bytes(&hex(v.ecdh_k)) else { return false };
            ux[..] == hex(v.ecc_ux)[..]
                && uy[..] == hex(v.ecc_uy)[..]
                && r[..] == hex(v.ecdsa_r)[..]
                && s[..] == hex(v.ecdsa_s)[..]
                && k.ecdh(&peer)[..] == hex(v.ecdh_zx)[..]
        }
        Family::Rsa => {
            let e = crypto::RSA_DEFAULT_EXPONENT;
            let Some(key) = RsaPrivate::from_prime(&hex(v.rsa_n), e, &hex(v.rsa_p)) else {
                return false;
            };
            let mut rng = PlatformRng::seeded(platform);
            let m = key.decrypt(&mut rng, RsaDecrypt::Raw, &hex(v.rsa_c));
            let digest = Hash::Sha256.digest(&[b"sample"]);
            let sig = key.sign(&mut rng, false, digest.as_slice());
            m.is_ok_and(|m| m[..] == hex(v.rsa_m)[..]) && sig == Some(hex(v.rsa_sig))
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    struct Zero;

    impl Platform for Zero {
        fn fill_random(&mut self, buf: &mut [u8]) {
            buf.fill(0);
        }
        fn now_ms(&mut self) -> u64 {
            0
        }
    }

    #[test]
    fn every_family_gives_its_known_answers() {
        for f in Family::ALL {
            assert!(check(f, &VECTORS, &mut Zero), "{f:?}");
        }
    }

    /// A family that answers wrongly is the failure, and the families after it go untested.
    #[test]
    fn a_wrong_answer_is_the_failure_and_stops_the_testing() {
        let mut v = VECTORS;
        v.aes_cfb = "3b3fd92eb72dad20333449f8e83cfb4ac8a64537a0b3a93fcde3cdad9f1ce58c";
        let mut t = ToTest::ALL;
        t.test_against(&[Family::Hash], &v, &mut Zero);
        assert_eq!(t.failed(), None);
        t.test_against(&Family::ALL, &v, &mut Zero);
        assert_eq!(t.failed(), Some(Family::Aes));
        assert_eq!(t.untested, Family::Aes.bit() | Family::Ecc.bit() | Family::Rsa.bit());
    }

    /// Each vector is compared: one wrong digit in any of them fails its family.
    #[test]
    fn a_wrong_expected_answer_fails_its_family() {
        type Field = for<'a, 'b> fn(&'b mut Vectors<'a>) -> &'b mut &'a str;
        let fields: [(Family, Field); 17] = [
            (Family::Hash, |v| &mut v.sha256_abc),
            (Family::Hash, |v| &mut v.hmac_jefe),
            (Family::Hash, |v| &mut v.kdfa),
            (Family::Hash, |v| &mut v.kdfe),
            (Family::Aes, |v| &mut v.aes_cfb),
            (Family::Ecc, |v| &mut v.ecc_x),
            (Family::Ecc, |v| &mut v.ecc_ux),
            (Family::Ecc, |v| &mut v.ecc_uy),
            (Family::Ecc, |v| &mut v.ecdsa_r),
            (Family::Ecc, |v| &mut v.ecdsa_s),
            (Family::Ecc, |v| &mut v.ecdh_k),
            (Family::Ecc, |v| &mut v.ecdh_zx),
            (Family::Rsa, |v| &mut v.rsa_n),
            (Family::Rsa, |v| &mut v.rsa_p),
            (Family::Rsa, |v| &mut v.rsa_c),
            (Family::Rsa, |v| &mut v.rsa_m),
            (Family::Rsa, |v| &mut v.rsa_sig),
        ];
        for (k, (family, field)) in fields.into_iter().enumerate() {
            let mut right = VECTORS;
            let wrong: String = field(&mut right)
                .chars()
                .enumerate()
                .map(|(i, c)| if i == 3 { if c == '0' { '1' } else { '0' } } else { c })
                .collect();
            let mut v = VECTORS;
            *field(&mut v) = &wrong;
            assert!(!check(family, &v, &mut Zero), "vector {k} of {family:?}");
        }
    }
}

#[cfg(kani)]
mod proofs {
    use super::*;

    /// For every buffer of up to 26 bytes and every failed family: the answer is a
    /// well-formed `TPM_ST_NO_SESSIONS` frame whose size is its length, and it succeeds only
    /// for a GetTestResult or GetCapability of exactly the size the reference parses.
    ///
    /// The property lookup walks the fixed-property table, so the bound must exceed its
    /// length.
    #[kani::proof]
    #[kani::unwind(48)]
    fn failure_mode_answers_every_buffer_with_a_frame() {
        let data: [u8; 26] = kani::any();
        let len: usize = kani::any_where(|l| *l <= 26);
        let failed = match kani::any::<u8>() % 4 {
            0 => Family::Hash,
            1 => Family::Aes,
            2 => Family::Ecc,
            _ => Family::Rsa,
        };
        let r = failure_answer(failed, &data[..len]);
        assert!(r.len() >= 10);
        assert!(r[0] == 0x80 && r[1] == 0x01);
        assert!(u32::from_be_bytes([r[2], r[3], r[4], r[5]]) as usize == r.len());
        let code = u32::from_be_bytes([r[6], r[7], r[8], r[9]]);
        assert!(code == 0 || code == TPM_RC_FAILURE);
        if code == 0 {
            let size = u32::from_be_bytes([data[2], data[3], data[4], data[5]]);
            let cc = u32::from_be_bytes([data[6], data[7], data[8], data[9]]);
            assert!((cc == 0x17C && size == 10) || (cc == 0x17A && size == 22 && len >= 22));
        }
    }
}
