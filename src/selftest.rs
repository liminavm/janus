//! Known-answer self-tests of the cryptography janus uses, by family, run before a family's
//! first use after `_TPM_Init` and by `TPM2_SelfTest`, as the reference tests an algorithm
//! before its first use (`TPM_DO_SELF_TEST`, `CryptSelfTest.c`). A wrong answer puts the TPM in
//! failure mode (`FATAL_ERROR_SELF_TEST`).
//!
//! The vectors come from outside the libraries under test: SHA-256 from FIPS 180-2, HMAC from
//! RFC 4231, AES-128-CFB from SP 800-38A, the ECDSA key and signature from RFC 6979; KDFa,
//! KDFe, the ECDH secret and the RSA key, ciphertext and signature were computed with Python's
//! `hashlib`/`hmac` and integer arithmetic, the RSA key generated by OpenSSL.

use crate::alg::Hash;
use crate::cc::Cc;
use crate::crypto::{self, EccPrivate, EccPublicKey, PlatformRng, RsaDecrypt, RsaPrivate};
use crate::rc::Fmt1;
use crate::wire::{Reader, Writer};
use crate::{Platform, SelfTests};

/// A family of algorithms tested together.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Family {
    /// SHA-256, HMAC-SHA-256, KDFa and KDFe.
    Hash = 1,
    /// AES-128 in CFB mode.
    Aes = 2,
    /// P-256: ECDSA signing and ECDH.
    Ecc = 3,
    /// RSA-2048: the private-key operation and PKCS#1 v1.5 signing.
    Rsa = 4,
}

impl Family {
    pub const ALL: [Family; 4] = [Family::Hash, Family::Aes, Family::Ecc, Family::Rsa];

    /// The low half of the failure location `TPM2_GetTestResult` reports.
    pub fn location(self) -> u32 {
        self as u32
    }

    const fn bit(self) -> u8 {
        1 << self as u8
    }

    /// The family `location` names.
    pub fn from_location(location: u8) -> Option<Family> {
        Family::ALL.into_iter().find(|f| f.location() == u32::from(location))
    }
}

/// The families not yet tested since `_TPM_Init` (`g_toTest`), and the one that failed, if
/// one did: from then until the next `_TPM_Init` the TPM is in failure mode.
#[derive(Clone, Copy)]
pub struct ToTest {
    untested: u8,
    failed: Option<Family>,
}

impl ToTest {
    /// Every family: after `_TPM_Init`, and for `TPM2_SelfTest(fullTest = YES)`.
    pub const ALL: ToTest = ToTest {
        untested: Family::Hash.bit() | Family::Aes.bit() | Family::Ecc.bit() | Family::Rsa.bit(),
        failed: None,
    };

    /// Tests each of `families` still untested, in order. The first that answers wrongly is
    /// the failure, and testing stops there.
    pub fn test(&mut self, families: &[Family], platform: &mut impl Platform) {
        self.test_against(families, &VECTORS, platform);
    }

    fn test_against(&mut self, families: &[Family], v: &Vectors<'_>, platform: &mut impl Platform) {
        for f in families {
            if self.untested & f.bit() == 0 {
                continue;
            }
            let passed = match platform.self_tests() {
                SelfTests::Run => check(*f, v, platform),
                SelfTests::Skip => true,
                SelfTests::Fail => false,
            };
            if !passed {
                self.failed = Some(*f);
                return;
            }
            self.untested &= !f.bit();
        }
    }

    /// `TPM2_SelfTest`: every family still untested, or all of them again for a full test
    /// (`CryptSelfTest`).
    pub fn self_test(&mut self, full: bool, platform: &mut impl Platform) {
        if full {
            self.untested = ToTest::ALL.untested;
        }
        self.test(&Family::ALL, platform);
    }

    pub fn failed(&self) -> Option<Family> {
        self.failed
    }

    /// In a snapshot: the untested families, then the one that failed, 0 for none.
    pub fn write(&self, w: &mut Writer) {
        w.u8(self.untested);
        w.u8(self.failed.map_or(0, |f| f as u8));
    }

    pub fn read(r: &mut Reader<'_>) -> Result<ToTest, Fmt1> {
        let untested = r.u8()?;
        if untested & !ToTest::ALL.untested != 0 {
            return Err(Fmt1::Value);
        }
        let failed = match r.u8()? {
            0 => None,
            f => Some(Family::from_location(f).ok_or(Fmt1::Value)?),
        };
        Ok(ToTest { untested, failed })
    }
}

/// The families a command may use, tested before it runs. Every command but the three that
/// need no cryptography may carry an HMAC session that encrypts a parameter; the ones that
/// can touch an asymmetric key may meet either kind.
pub fn families(cc: Cc) -> &'static [Family] {
    match cc {
        Cc::GetCapability | Cc::GetTestResult | Cc::SelfTest => &[],
        Cc::CreatePrimary
        | Cc::Create
        | Cc::Load
        | Cc::ContextLoad
        | Cc::Sign
        | Cc::RsaDecrypt
        | Cc::StartAuthSession => &Family::ALL,
        _ => &[Family::Hash, Family::Aes],
    }
}

/// `FATAL_ERROR_SELF_TEST`, the failure code `TPM2_GetTestResult` reports.
const FATAL_ERROR_SELF_TEST: u32 = 6;
const TPM_ST_NO_SESSIONS: u16 = 0x8001;
const TPM_RC_FAILURE: u32 = 0x101;
const TPM_CAP_TPM_PROPERTIES: u32 = 6;
const TPM_PT_MANUFACTURER: u32 = 0x105;
const TPM_PT_FIRMWARE_VERSION_2: u32 = 0x10C;

/// What a TPM in failure mode answers (`TpmFailureMode`): `TPM2_GetTestResult` reports the
/// failure, `TPM2_GetCapability` gives one vendor property at a time, and anything else, or
/// either of those not exactly as the reference parses it, is `TPM_RC_FAILURE`.
///
/// One departure: for a count of zero the reference still writes a property and a value after
/// a list that declares none, which no parser accepts; here the list is empty. And it answers a
/// property past `FIRMWARE_VERSION_2` with that property's tag and `FIRMWARE_VERSION_2`'s
/// value; here, as its own comment intends, such a request gets an empty list.
pub fn failure_answer(failed: Family, bytes: &[u8]) -> Vec<u8> {
    let be32 = |at: usize| {
        bytes.get(at..at + 4).map(|b| u32::from_be_bytes(b.try_into().expect("four bytes")))
    };
    let tag = bytes.get(..2).map(|b| u16::from_be_bytes([b[0], b[1]]));
    let mut out = Vec::new();
    // Like the reference, the header's size is checked against what each command must be,
    // not against what arrived: a longer buffer is read only as far as the size says.
    match (tag, be32(2), be32(6)) {
        (Some(TPM_ST_NO_SESSIONS), Some(10), Some(0x17C)) => {
            out.extend_from_slice(&12u16.to_be_bytes());
            out.extend_from_slice(&0u32.to_be_bytes());
            out.extend_from_slice(&failed.location().to_be_bytes());
            out.extend_from_slice(&FATAL_ERROR_SELF_TEST.to_be_bytes());
            out.extend_from_slice(&TPM_RC_FAILURE.to_be_bytes());
        }
        (Some(TPM_ST_NO_SESSIONS), Some(22), Some(0x17A)) => {
            let (Some(TPM_CAP_TPM_PROPERTIES), Some(pt), Some(count)) =
                (be32(10), be32(14), be32(18))
            else {
                return failure();
            };
            let pt = pt.max(TPM_PT_MANUFACTURER);
            let one = count > 0 && pt <= TPM_PT_FIRMWARE_VERSION_2;
            out.push(u8::from(pt < TPM_PT_FIRMWARE_VERSION_2));
            out.extend_from_slice(&TPM_CAP_TPM_PROPERTIES.to_be_bytes());
            out.extend_from_slice(&u32::from(one).to_be_bytes());
            if one {
                let value = crate::capability::fixed(pt).expect("a vendor property is fixed");
                out.extend_from_slice(&pt.to_be_bytes());
                out.extend_from_slice(&value.to_be_bytes());
            }
        }
        _ => return failure(),
    }
    let mut r = Vec::with_capacity(10 + out.len());
    r.extend_from_slice(&TPM_ST_NO_SESSIONS.to_be_bytes());
    r.extend_from_slice(&(10 + out.len() as u32).to_be_bytes());
    r.extend_from_slice(&0u32.to_be_bytes());
    r.extend_from_slice(&out);
    r
}

fn failure() -> Vec<u8> {
    let mut r = Vec::with_capacity(10);
    r.extend_from_slice(&TPM_ST_NO_SESSIONS.to_be_bytes());
    r.extend_from_slice(&10u32.to_be_bytes());
    r.extend_from_slice(&TPM_RC_FAILURE.to_be_bytes());
    r
}

